class _01_pattern{
    public static void main(String args[]){
        /*
        * * * * *
        * * * * *
        * * * * *
        * * * * *
        */
       // hear r = 4 , c = 5
       // raw - outer loop
       // clumn - inner loop

        for(int i=1; i<=4; i++){
            for(int j=1; j<=5; j++){
                System.out.print("* ");

            }
            System.out.println();
        }
    }
}